const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createServer } = require('node:http');
const { readFile, mkdir } = require('node:fs/promises');
const { resolve, join, extname } = require('node:path');
const { tmpdir } = require('node:os');
const { crc32 } = require('node:zlib');
const { chromium } = require('playwright-core');

test('image compression, recovery, inspector, downloads and mobile regression', { timeout: 120000 }, async t => {
  const root = resolve(__dirname, '../dist');
  const server = createServer(async (req, res) => {
    try {
      const path = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
      const file = resolve(root, '.' + (path === '/' ? '/index.html' : path));
      if (!file.startsWith(root + require('node:path').sep)) throw new Error('Invalid path');
      const data = await readFile(file);
      const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' };
      res.setHeader('Content-Type', types[extname(file)] || 'application/octet-stream');
      res.end(data);
    } catch { res.writeHead(404); res.end(); }
  });
  await new Promise(done => server.listen(0, '127.0.0.1', done));
  t.after(() => new Promise(done => server.close(done)));
  const browser = await chromium.launch(process.env.BROWSER_PATH
    ? { executablePath: process.env.BROWSER_PATH, headless: true }
    : { channel: 'msedge', headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], external = [], failedRequests = [];
  page.on('console', message => {
    if (message.text().startsWith('QA:')) console.log(message.text());
  });
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) failedRequests.push(response.url()); });
  await page.route('**/*', route => {
    if (/^https?:/.test(route.request().url()) && !route.request().url().startsWith('http://127.0.0.1:')) {
      external.push(route.request().url()); return route.abort();
    }
    return route.continue();
  });
  const url = `http://127.0.0.1:${server.address().port}/`;
  await page.goto(url);
  await page.waitForFunction(() => state.items.length === 2 && !processing);
  assert.match(await page.title(), /Compress Image/);
  assert.equal(await page.locator('article').count(), 2);
  assert.equal(await page.locator('#processingStatus').isVisible(), false);
  const output = process.env.QA_OUTPUT || join(tmpdir(), 'pixel-press-qa');
  await mkdir(output, { recursive: true });

  await t.test('languages and initial sample target', async () => {
    assert.ok(await page.evaluate(() => state.items[1].compSize <= 150 * 1024));
    for (const lang of ['zh', 'ja', 'es', 'en']) {
      await page.selectOption('#langSelect', lang);
      assert.equal(await page.locator('html').getAttribute('lang'), lang === 'zh' ? 'zh-CN' : lang);
      assert.doesNotMatch(await page.locator('body').innerText(), /undefined|NaN/);
    }
  });

  // Fixtures are generated by the browser, without network or image libraries.
  const png = Buffer.from(await page.evaluate(async () => {
    const c = document.createElement('canvas'); c.width = 160; c.height = 80;
    const ctx = c.getContext('2d'); ctx.fillStyle = '#ff0000'; ctx.fillRect(0, 0, 80, 80);
    const blob = await new Promise(done => c.toBlob(done, 'image/png'));
    return [...new Uint8Array(await blob.arrayBuffer())];
  }));

  await t.test('malicious filename, MIME inference and damaged batch member', async () => {
    await page.locator('#fileInput').setInputFiles([
      { name: '<img src=x onerror=alert(1)>.png', mimeType: '', buffer: png },
      { name: 'damaged.png', mimeType: 'image/png', buffer: Buffer.from('not an image') },
      { name: 'valid.png', mimeType: 'image/png', buffer: png }
    ]);
    await page.waitForFunction(() => !processing && state.items.length === 2 && !state.items[0].isSample);
    assert.equal(await page.locator('img[src="x"]').count(), 0);
    assert.match(await page.locator('#toastMessage').innerText(), /skipped 1/);
    assert.ok(await page.evaluate(() => state.items.every(item => item.origFormat === 'image/png')));
  });

  await t.test('PNG scale, transparency, target limits and concurrent operations', async () => {
    const result = await page.evaluate(async () => {
      await setCardManualQuality(0, 15);
      const scaled = { scale: state.items[0].activeScale, width: state.items[0].outWidth, height: state.items[0].outHeight };
      await Promise.all([setCardFormat(0, 'image/jpeg'), setCardFormat(0, 'image/webp'), clearAllImages()]);
      const item = state.items[0];
      const matching = item.outFormat === item.compBlob.type;
      const image = await decodeHtmlImage(item.compUrl);
      const c = document.createElement('canvas'); c.width = image.width; c.height = image.height;
      const ctx = c.getContext('2d'); ctx.drawImage(image, 0, 0);
      const white = [...ctx.getImageData(image.width - 1, 0, 1, 1).data];
      await setCardTargetKB(0, 10);
      const targetHit = item.compSize <= 10 * 1024;
      await setCardTargetKB(0, Infinity);
      return { scaled, matching, white, targetHit, normalized: item.targetKB, count: state.items.length };
    });
    assert.ok(result.scaled.scale < 1);
    assert.ok(Math.abs(result.scaled.width / result.scaled.height - 2) < .05);
    assert.ok(result.matching);
    assert.ok(result.white.slice(0, 3).every(channel => channel >= 250));
    assert.equal(result.white[3], 255);
    assert.ok(result.targetHit);
    assert.equal(result.normalized, 150);
    assert.equal(result.count, 2);
  });

  await t.test('encoder failure rolls back and subsequent operation succeeds', async () => {
    assert.ok(await page.evaluate(async () => {
      const original = encodeCandidate;
      const previous = state.items[0].outFormat;
      encodeCandidate = async () => { throw new Error('Simulated encoder failure'); };
      await setCardFormat(0, 'image/webp');
      encodeCandidate = original;
      const recovered = state.items[0].outFormat === previous && !processing;
      await decodeHtmlImage(state.items[0].compUrl);
      await setCardFormat(0, 'image/webp');
      return recovered && state.items[0].compBlob.type === 'image/webp';
    }));
  });

  await t.test('batch formats and strict target fallback on photographic samples', async () => {
    const results = await page.evaluate(async () => {
      // Preserve upload fixtures for the inspector and download tests below.
      const uploads = state.items;
      state.items = [];
      await addSampleSpecimens(['landscape', 'portrait']);
      const results = [];
      for (const format of ['image/jpeg', 'image/webp', 'image/png']) {
        console.log('QA: batch format ' + format);
        await applyGlobalFormat(format);
        await applyGlobalStrategy('target', 10);
        results.push(state.items.every(item => item.compBlob.type === format && item.compSize <= 10240 && item.outWidth <= item.width && item.outHeight <= item.height));
      }
      await applyGlobalFormat('auto');
      results.push(state.items[0].outFormat === 'image/jpeg' && state.items[1].outFormat === 'image/webp');
      await applyGlobalFormat('original');
      results.push(state.items.every(item => item.outFormat === item.origFormat));
      await applyGlobalStrategy('knee');
      results.push(state.items.every(item => item.mode === 'knee'));
      state.items.forEach(revokeItemUrls);
      state.items = uploads;
      renderWorkspace();
      return results;
    });
    assert.ok(results.every(Boolean));
  });

  await t.test('inspector modes, rapid switching, zoom and keyboard close', async () => {
    await page.locator('article button[onclick="openLightbox(0, \'split\')"]').click();
    await page.waitForFunction(() => state.lightbox.isOpen && document.getElementById('lbBaseImg').width > 0);
    await page.evaluate(async () => {
      await Promise.all([setLightboxViewMode('diff'), setLightboxViewMode('orig'), setLightboxViewMode('comp')]);
    });
    assert.equal(await page.locator('#lbDiffCanvas').isVisible(), false);
    await page.locator('#lbModeDiff').click();
    await page.waitForFunction(() => !document.getElementById('lbDiffCanvas').classList.contains('hidden'));
    assert.ok(await page.locator('#lbDiffCanvas').isVisible());
    await page.evaluate(() => stepLightboxImage(1));
    assert.equal(await page.locator('#lbImageCounter').innerText(), '2 / 2');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(() => !processing);
    await page.evaluate(() => zoomLightboxBy(100));
    assert.equal(await page.evaluate(() => state.lightbox.scale), 4);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#lightboxModal').isVisible(), false);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
  });

  await t.test('single download and ZIP signatures, unique names and CRC', async () => {
    const singleEvent = page.waitForEvent('download');
    await page.locator('button[onclick="downloadSingleItem(0)"]').click();
    const single = await singleEvent;
    assert.match(single.suggestedFilename(), /\.webp$/);
    const singleBytes = await readFile(await single.path());
    assert.equal(singleBytes.subarray(8, 12).toString(), 'WEBP');
    await page.evaluate(() => {
      const a = state.items[0];
      const base = buildOutputFilename(a).replace(/\.[^.]+$/, '');
      state.items[1].name = a.name;
      state.items.push({ ...a }, { ...a, name: base + '-1.webp' });
    });
    const zipEvent = page.waitForEvent('download');
    await page.locator('#downloadAllZipBtn').click();
    const zip = await readFile(await (await zipEvent).path());
    const names = [];
    let offset = 0;
    while (zip.readUInt32LE(offset) === 0x04034b50) {
      const size = zip.readUInt32LE(offset + 18);
      const length = zip.readUInt16LE(offset + 26);
      names.push(zip.subarray(offset + 30, offset + 30 + length).toString());
      const data = zip.subarray(offset + 30 + length, offset + 30 + length + size);
      assert.equal(crc32(data), zip.readUInt32LE(offset + 14));
      offset += 30 + length + size;
    }
    assert.equal(names.length, 4);
    assert.equal(new Set(names.map(name => name.toLowerCase())).size, 4);
    assert.equal(zip.readUInt32LE(offset), 0x02014b50);
    assert.equal(zip.readUInt32LE(zip.length - 22), 0x06054b50);
    assert.equal(zip.readUInt16LE(zip.length - 12), 4);
  });

  await t.test('tiny image keeps dimensions and mobile has no horizontal overflow', async () => {
    await page.evaluate(async () => {
      await clearAllImages();
      const c = document.createElement('canvas'); c.width = 2; c.height = 1;
      const blob = await new Promise(done => c.toBlob(done));
      await ingestFileList([new File([blob], 'tiny.png', { type: 'image/png' })]);
      await setCardManualQuality(0, 95);
    });
    assert.deepEqual(await page.evaluate(() => [state.items[0].outWidth, state.items[0].outHeight]), [2, 1]);
    await page.evaluate(() => scrollTo(0, 0));
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));

    await page.evaluate(() => openLightbox(0, 'split'));
    assert.ok(await page.locator('[data-i18n-title="closeInspector"]').isVisible());
    await page.keyboard.press('Escape');
    await page.evaluate(() => clearAllImages());
    assert.ok(await page.locator('#emptyWorkspaceBox').isVisible());
    await page.evaluate(() => addSampleSpecimens(['landscape', 'portrait']));
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: join(output, 'mobile.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: join(output, 'desktop.png') });
    console.log(`QA screenshots: ${output}`);
  });
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  assert.deepEqual(failedRequests, []);
  console.log(`Verified: ${url}, desktop 1440x1000, mobile 390x844; no external requests or page errors.`);
});
